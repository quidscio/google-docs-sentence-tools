'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const sourceFiles = ['SentenceEngine.js', 'Code.js'];
const header = '/**\n * @OnlyCurrentDoc\n * Generated by npm run build. Edit files in src/ instead.\n */\n';
const source = sourceFiles.map((name) => {
  const contents = fs.readFileSync(path.join(root, 'src', name), 'utf8');
  return '\n// Source: ' + name + '\n' + contents.trimEnd() + '\n';
}).join('\n');
const bundle = header + source;

// Catch syntax errors before writing a deployment artifact. The Apps Script
// services are resolved only when the generated functions run in Google Docs.
new vm.Script(bundle, { filename: 'Code.gs' });
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'src', 'appsscript.json'), 'utf8'));
const outputDirectory = path.join(root, 'dist');
fs.mkdirSync(outputDirectory, { recursive: true });
fs.writeFileSync(path.join(outputDirectory, 'Code.gs'), bundle, 'utf8');
fs.writeFileSync(path.join(outputDirectory, 'appsscript.json'), JSON.stringify(manifest, null, 2) + '\n', 'utf8');
console.log('Built dist/Code.gs and dist/appsscript.json.');
