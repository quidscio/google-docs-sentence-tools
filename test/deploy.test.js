'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { parseArgs, readConfig, validateArtifact, runWorkflow } = require('../scripts/deploy.js');

const SCRIPT_ID = '1SentenceToolsExampleProject_1234567890';
const OTHER_ID = '1DifferentExampleProject_1234567890';
const sourceManifest = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'src', 'appsscript.json'), 'utf8'));

function fixture(t) {
  const tempDirectory = path.resolve(os.tmpdir());
  const root = fs.mkdtempSync(path.join(tempDirectory, 'sentence-tools-deploy-'));
  t.after(() => {
    const resolved = path.resolve(root);
    assert.equal(path.dirname(resolved), tempDirectory);
    assert.ok(path.basename(resolved).startsWith('sentence-tools-deploy-'));
    fs.rmSync(resolved, { recursive: true, force: true });
  });
  const dist = path.join(root, 'dist');
  const configFile = path.join(root, '.clasp.json');
  const pendingFile = path.join(root, '.clasp-create-pending.json');
  const manifestFile = path.join(dist, 'appsscript.json');
  const calls = [];
  const logs = [];
  let builds = 0;
  fs.mkdirSync(dist);

  function restoreArtifact() {
    fs.writeFileSync(path.join(dist, 'Code.gs'), 'function onHomepage() {}\n');
    fs.writeFileSync(manifestFile, JSON.stringify(sourceManifest, null, 2));
  }
  restoreArtifact();

  function writeConfig(overrides = {}) {
    // These are the settings generated by clasp 3.4.1, including its ordinary
    // extension defaults. A mock with only two fields missed a real setup bug.
    const config = {
      scriptId: SCRIPT_ID,
      rootDir: 'dist',
      scriptExtensions: ['.js', '.gs'],
      htmlExtensions: ['.html'],
      jsonExtensions: ['.json'],
      filePushOrder: [],
      skipSubdirectories: false,
      ...overrides
    };
    fs.writeFileSync(configFile, JSON.stringify(config, null, 2));
    return config;
  }

  const behavior = {
    loggedIn: true,
    status: () => ({ filesToPush: [path.join(dist, 'Code.gs'), manifestFile], untrackedFiles: [] }),
    pushed: () => [path.join(dist, 'Code.gs'), manifestFile],
    create: () => {
      writeConfig();
      fs.writeFileSync(manifestFile, JSON.stringify({ timeZone: 'Etc/UTC', runtimeVersion: 'V8' }));
      fs.writeFileSync(path.join(dist, 'Code.js'), 'function myFunction() {}\n');
      return { scriptId: SCRIPT_ID, files: [path.join(dist, 'Code.js'), manifestFile] };
    },
    open: () => ''
  };
  const dependencies = {
    run(args, json = true) {
      calls.push({ args: args.slice(), json });
      switch (args[0]) {
        case 'show-authorized-user':
          return { loggedIn: behavior.loggedIn, email: behavior.loggedIn ? 'test@example.com' : undefined };
        case 'create-script': return behavior.create(args);
        case 'show-file-status': return behavior.status();
        case 'push': return behavior.pushed(args);
        case 'open-script': return behavior.open();
        default: throw new Error('Unexpected clasp command: ' + args.join(' '));
      }
    },
    build() { builds += 1; restoreArtifact(); },
    log(message) { logs.push(message); }
  };
  return {
    root, dist, configFile, pendingFile, manifestFile, calls, logs, behavior, dependencies,
    writeConfig, builds: () => builds,
    commands: () => calls.map(call => call.args[0]),
    run: args => runWorkflow(root, parseArgs(args), dependencies)
  };
}

test('setup dry-run leaves files and account untouched, including an explicit Script ID', t => {
  const state = fixture(t);
  const before = fs.readFileSync(state.manifestFile, 'utf8');
  assert.deepEqual(state.run(['setup', '--dry-run']), { dryRun: true });
  assert.deepEqual(state.run(['setup', '--script-id', SCRIPT_ID, '--dry-run']), { dryRun: true });
  assert.deepEqual(state.calls, []);
  assert.equal(state.builds(), 0);
  assert.equal(fs.existsSync(state.configFile), false);
  assert.equal(fs.readFileSync(state.manifestFile, 'utf8'), before);
  assert.ok(state.logs.some(message => /Would create/.test(message)));
});

