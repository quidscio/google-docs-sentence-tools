test('explicit-ID recovery preserves pending files in dry-run and without auth, then repairs the build', t => {
  const state = fixture(t);
  const starterFile = path.join(state.dist, 'Code.js');
  state.behavior.create = () => {
    fs.writeFileSync(starterFile, 'function myFunction() {}\n');
    fs.writeFileSync(state.manifestFile, JSON.stringify({ runtimeVersion: 'V8', timeZone: 'Etc/UTC' }));
    throw new Error('Creation response interrupted before config was saved');
  };
  assert.throws(() => state.run(['setup']), /interrupted/);
  const pendingBefore = fs.readFileSync(state.pendingFile, 'utf8');
  const starterBefore = fs.readFileSync(starterFile, 'utf8');
  const manifestBefore = fs.readFileSync(state.manifestFile, 'utf8');
  state.calls.length = 0;
  state.run(['setup', '--script-id', SCRIPT_ID, '--dry-run']);
  assert.deepEqual(state.calls, []);
  state.behavior.loggedIn = false;
  assert.throws(() => state.run(['setup', '--script-id', SCRIPT_ID]), /Sign in first/i);
  assert.equal(fs.readFileSync(state.pendingFile, 'utf8'), pendingBefore);
  assert.equal(fs.readFileSync(starterFile, 'utf8'), starterBefore);
  assert.equal(fs.readFileSync(state.manifestFile, 'utf8'), manifestBefore);
  assert.equal(fs.existsSync(state.configFile), false);
  assert.equal(state.builds(), 0);

  state.behavior.loggedIn = true;
  state.calls.length = 0;
  const result = state.run(['setup', '--script-id', SCRIPT_ID, '--no-open']);
  assert.equal(result.scriptId, SCRIPT_ID);
  assert.deepEqual(state.commands(), ['show-authorized-user', 'show-file-status', 'push']);
  assert.equal(state.builds(), 1);
  assert.deepEqual(JSON.parse(fs.readFileSync(state.manifestFile, 'utf8')), sourceManifest);
  assert.equal(fs.existsSync(starterFile), false);
  assert.equal(fs.existsSync(state.pendingFile), false);
});

test('a pending attempt with saved clasp configuration repairs local files without another creation', t => {
  const state = fixture(t);
  const create = state.behavior.create;
  state.behavior.create = () => {
    create();
    throw new Error('Connection lost after clasp saved the project');
  };
  assert.throws(() => state.run(['setup']), /Connection lost/);
  assert.equal(readConfig(state.root).scriptId, SCRIPT_ID);
  assert.equal(fs.existsSync(state.pendingFile), true);
  assert.equal(fs.existsSync(path.join(state.dist, 'Code.js')), true);
  state.calls.length = 0;
  const result = state.run(['setup', '--no-open']);
  assert.equal(result.scriptId, SCRIPT_ID);
  assert.deepEqual(state.commands(), ['show-authorized-user', 'show-file-status', 'push']);
  assert.equal(state.builds(), 1);
  assert.deepEqual(JSON.parse(fs.readFileSync(state.manifestFile, 'utf8')), sourceManifest);
  assert.equal(fs.existsSync(path.join(state.dist, 'Code.js')), false);
  assert.equal(fs.existsSync(state.pendingFile), false);
});

test('explicit retry-create allows another attempt after the user has checked no project exists', t => {
  const state = fixture(t);
  const create = state.behavior.create;
  state.behavior.create = () => { throw new Error('Create request failed before reaching the server'); };
  assert.throws(() => state.run(['setup']), /Create request failed/);
  assert.equal(fs.existsSync(state.pendingFile), true);
  state.behavior.create = create;
  state.calls.length = 0;
  const result = state.run(['setup', '--retry-create', '--no-open']);
  assert.equal(result.scriptId, SCRIPT_ID);
  assert.deepEqual(state.commands(), ['show-authorized-user', 'create-script', 'show-file-status', 'push']);
  assert.equal(fs.existsSync(state.pendingFile), false);
});
