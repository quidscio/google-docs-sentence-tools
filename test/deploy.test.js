test('setup without authorization cannot create, link, or upload a project', t => {
  const state = fixture(t);
  state.behavior.loggedIn = false;
  assert.throws(() => state.run(['setup']), /Sign in first/i);
  assert.throws(() => state.run(['setup', '--script-id', SCRIPT_ID]), /Sign in first/i);
  assert.deepEqual(state.commands(), ['show-authorized-user', 'show-authorized-user']);
  assert.equal(fs.existsSync(state.configFile), false);
  assert.equal(state.builds(), 0);
});

test('new standalone setup accepts real clasp defaults and restores the add-on before upload', t => {
  const state = fixture(t);
  state.behavior.pushed = args => {
    assert.deepEqual(args, ['push', '--force']);
    assert.equal(state.builds(), 1);
    assert.deepEqual(JSON.parse(fs.readFileSync(state.manifestFile, 'utf8')), sourceManifest);
    assert.equal(fs.existsSync(path.join(state.dist, 'Code.js')), false);
    return [path.join(state.dist, 'Code.gs'), state.manifestFile];
  };
  const result = state.run(['setup']);
  assert.deepEqual(state.commands(), [
    'show-authorized-user', 'create-script', 'show-file-status', 'push', 'open-script'
  ]);
  assert.deepEqual(state.calls[1].args, [
    'create-script', '--type', 'standalone', '--title', 'Sentence Tools', '--rootDir', 'dist'
  ]);
  assert.equal(state.calls.at(-1).json, false);
  assert.equal(readConfig(state.root).scriptId, SCRIPT_ID);
  assert.equal(result.scriptId, SCRIPT_ID);
  assert.ok(result.editorUrl.includes(SCRIPT_ID));
  assert.ok(state.logs.some(message => /Install once/.test(message)));
  assert.equal(fs.existsSync(state.pendingFile), false);
});

